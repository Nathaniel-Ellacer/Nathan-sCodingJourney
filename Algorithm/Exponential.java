package Algorithm;
public class Exponential {
    public static void main(String[] args) {
        double value = 5.0d; // Changed input value
        System.out.println(Math.log(value)); // Natural logarithm
        
        double baseValue = 3.0d; // Changed base value
        double powerExponent = 2.0d; // Changed exponent
        System.out.println(Math.pow(baseValue, powerExponent)); // Power function
    }
}

    